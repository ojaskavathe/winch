import "github.com/mattn/go-runewidth"

// Cell widths must match tmux's, or emulated rewraps (emulate.go) drift off
// the real reflow by a column per odd rune — the oracle test caught exactly
// that on U+26A1. tmux resolves a rune's width as: its own override table
// first, then utf8proc_wcwidth (the nixpkgs build links utf8proc).
// go-runewidth tracks the same Unicode EastAsianWidth data as utf8proc, and
// tmuxWidthOverride below is generated from utf8_default_width_cache in tmux
// 3.7b's utf8.c — mostly emoji forced wide, regional indicators forced
// narrow.
func runeWidth(r rune) int {
	if w, ok := tmuxWidthOverride[r]; ok {
		return w
	}
	return runewidth.RuneWidth(r)
}

